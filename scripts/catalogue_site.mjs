#!/usr/bin/env node
// data/catalogue.tsv -> docs/assets/instances.js (the benchmark list of the Solver page). The instance files themselves are
// bundled under docs/data/ so the Solver does not depend on third-party hosts; `source` keeps the original URL for attribution.
//   node scripts/catalogue_site.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VRP = createRequire(import.meta.url)(path.join(ROOT, 'docs', 'assets', 'vrp.js'));
const setOf = (name, kind) => kind === 'mdvrp' ? 'cordeau' : /^X-/.test(name) ? 'x' : /^CMT/.test(name) ? 'cmt' : /^Golden/.test(name) ? 'golden' : 'other';
const lines = fs.readFileSync(path.join(ROOT, 'data', 'catalogue.tsv'), 'utf8').split('\n').filter(l => l.length);
const head = lines[0].split('\t');
const out = lines.slice(1).map(l => {
  const o = Object.fromEntries(l.split('\t').map((v, i) => [head[i], v]));
  const status = /^verified/.test(o.bks_status) ? 'verified' : /^secondary/.test(o.bks_status) ? 'secondary' : 'unverified';
  if (!fs.existsSync(path.join(ROOT, 'docs', 'data', o.file))) throw new Error('missing docs/data/' + o.file);
  const I = VRP.parseInstance(fs.readFileSync(path.join(ROOT, 'docs', 'data', o.file), 'utf8'), o.name);   // size and limits for the list
  return { name: o.name, kind: o.kind, set: setOf(o.name, o.kind), n: I.n, depots: I.t, limit: isFinite(I.Dmax[0]), url: 'data/' + o.file, source: o.url, bks: o.bks === '-' ? null : parseFloat(o.bks), bksStatus: status, bksNote: o.bks_status + (o.bks_source ? ' · ' + o.bks_source : '') };
});
fs.writeFileSync(path.join(ROOT, 'docs', 'assets', 'instances.js'),
  '/* generated by scripts/catalogue_site.mjs from data/catalogue.tsv - do not edit */\nwindow.VRP_INSTANCES = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('wrote docs/assets/instances.js with', out.length, 'instances');
